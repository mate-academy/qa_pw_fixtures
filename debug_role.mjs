import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('https://conduit.mate.academy/user/register');
const username = 'debuguser' + Date.now();
const email = username + '@example.com';
const password = 'Password123!';
await page.fill('input[placeholder="Username"]', username);
await page.fill('input[placeholder="Email"]', email);
await page.fill('input[placeholder="Password"]', password);
await page.click('button:has-text("Sign up")');
await page.waitForLoadState('networkidle');
console.log('URL after sign-up', page.url());
const element = page.locator('a:has-text("Your Feed")').first();
console.log('count', await element.count());
console.log('outerHTML', await element.evaluate(el => el.outerHTML));
console.log('role', await element.evaluate(el => el.getAttribute('role')));
console.log('text', await element.evaluate(el => el.textContent));
await browser.close();
