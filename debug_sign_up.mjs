import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('https://conduit.mate.academy/user/register');
const username = 'testuser' + Date.now();
const email = username + '@example.com';
const password = 'Password123!';
console.log('filling', username, email);
await page.locator('input[placeholder="Username"]').fill(username);
await page.locator('input[placeholder="Email"]').fill(email);
await page.locator('input[placeholder="Password"]').fill(password);
await page.locator('button:has-text("Sign up")').click();
await page.waitForLoadState('networkidle');
await page.screenshot({ path: 'debug-signup-after.png', fullPage: true });
console.log('URL after sign-up', page.url());
console.log('Your Feed count after sign-up', await page.locator('a:has-text("Your Feed")').count());
console.log('Global Feed count after sign-up', await page.locator('a:has-text("Global Feed")').count());
console.log('Home count after sign-up', await page.locator('a:has-text("Home")').count());
const bodyText = await page.locator('body').innerText();
console.log('body after sign-up first 400 chars:\n', bodyText.slice(0,400));
await browser.close();
